#[test]
fn a_duplicate_promotion_is_an_error() {
    let journal = "\
| [E030](E030-a.md) | 2026-10-16 | A | Accepted | Promoted: `uttt-v017` |
| [E031](E031-b.md) | 2026-10-16 | B | Accepted | Promoted: `uttt-v017` |
";
    let err = parse_journal(journal, "uttt").unwrap_err();
    assert!(err.contains("uttt-v017") && err.contains("E030") && err.contains("E031"));
    let err = render("uttt", &[], &[], "random", journal, &releases(&[])).unwrap_err();
    assert!(err.contains("twice"));
}

