#[test]
fn rates_a_results_file_end_to_end() {
    let pairings = [
        pairing("v002", "v001", 150, 20, 30),
        pairing("v001", "random", 190, 0, 10),
        pairing("v002", "random", 198, 0, 2),
    ];
    let names = league::known_bots(&pairings, ["random"]);
    let ratings = league::rate(&names, &pairings, "random").unwrap();
    let both = releases(&["v001", "v002"]);
    let first = render("uttt", &pairings, &ratings, "random", JOURNAL, &both).unwrap();
    let again = render("uttt", &pairings, &ratings, "random", JOURNAL, &both).unwrap();
    assert_eq!(first, again);
    let rows: Vec<&str> = first.text.lines().skip(6).collect();
    assert_eq!(rows.len(), 3);
    assert!(rows[0].starts_with("| 1 | [v002](releases/uttt-v002.rs) | +"));
    assert!(rows[1].starts_with("| 2 | [v001](releases/uttt-v001.rs) | +"));
    assert!(rows[2].starts_with("| 3 | random | 0.0 | anchor | 400 |"));
    assert!(first.text.contains("over 3 pairings and 600 games"));
    assert_eq!(first.warnings.len(), 2);
}

#[test]
fn the_real_journal_promotes_every_uttt_release() {
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../games/uttt/journal/README.md");
    let text = std::fs::read_to_string(&path).unwrap();
    let entries = parse_journal(&text, "uttt").unwrap();
    for number in 1..=18 {
        let release = format!("v{number:03}");
        assert!(
            entries.contains_key(&release),
            "no row promotes uttt-{release}"
        );
    }
    assert_eq!(entries["v001"].experiment, "E001");
    assert_eq!(entries["v001"].target, "E001-mcts.md");
    assert_eq!(entries["v001"].date, "2026-10-07");
    assert_eq!(entries["v018"].experiment, "E032");
    assert_eq!(entries["v018"].target, "E032-puct-tuning.md");
}
