#[test]
fn time_limits_are_shown_or_reported_as_mixed() {
    let ratings = [rating("random", 0.0, 0.0, 400)];
    let render_text = |pairings: &[PairingResult]| {
        render("uttt", pairings, &ratings, "random", "", &releases(&[]))
            .unwrap()
            .text
    };

    let mut slow = pairing("v017", "random", 100, 0, 100);
    slow.time_scale = 0.2;
    assert!(render_text(&[slow.clone()])
        .contains("Time limits: time scale 0.2, tolerance 0 ms, 4 opening plies."));

    let normal = pairing("v018", "random", 100, 0, 100);
    let mut tolerant = normal.clone();
    tolerant.time_tolerance_ms = 5;
    let mut plies = normal.clone();
    plies.opening_plies = 6;
    for other in [slow, tolerant, plies] {
        let text = render_text(&[normal.clone(), other]);
        assert!(
            text.contains("Time limits: mixed (see league.jsonl)."),
            "{text}"
        );
    }
}

