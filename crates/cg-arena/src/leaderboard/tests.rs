const JOURNAL: &str = "\
# Journal

| Entry | Date | Hypothesis | SPRT | Decision |
| --- | --- | --- | --- | --- |
| [E030](E030-puct.md) | 2026-10-16 | PUCT | Accepted | Promoted: `uttt-v017` |
| [E031](E031-dropped.md) | 2026-10-16 | Dropped | Rejected | Promoted: none |
| [E032](E032-puct-tuning.md) | 2026-10-16 | Tuning | Accepted | Promoted: `uttt-v018` |
| broken row | Promoted: `uttt-v019` |
| [E033](E033-x.md) | not a date | Odd | Accepted | Promoted: `uttt-v020` |
| E034 | 2026-10-16 | No link | Accepted | Promoted: `uttt-v021` |
| [E035](E035-x.md) | 2026-10-16 | Other game | Accepted | Promoted: `other-v001` |
";

fn rating(name: &str, rating: f64, margin: f64, games: u32) -> Rating {
    Rating {
        name: name.to_string(),
        rating,
        margin,
        games,
    }
}

fn pairing(a: &str, b: &str, wins: u32, draws: u32, losses: u32) -> PairingResult {
    let pairs = (wins + draws + losses) / 2;
    PairingResult {
        a: a.to_string(),
        b: b.to_string(),
        pairs,
        wins,
        draws,
        losses,
        pair_points: [0, 0, pairs, 0, 0],
        faults: [0, 0],
        time_scale: 1.0,
        time_tolerance_ms: 0,
        opening_plies: 4,
        seed: 1,
        date: "2026-10-16".to_string(),
        commit: "unknown".to_string(),
        cpu: "unknown".to_string(),
    }
}

fn releases(names: &[&str]) -> BTreeSet<String> {
    names.iter().map(|name| name.to_string()).collect()
}

/// `count` pairings of 100 pairs each, between bots that are not rated.
fn filler(count: usize) -> Vec<PairingResult> {
    (0..count)
        .map(|at| pairing(&format!("x{at}"), "y", 100, 0, 100))
        .collect()
}

#[test]
fn thousands_separators() {
    assert_eq!(thousands(0), "0");
    assert_eq!(thousands(999), "999");
    assert_eq!(thousands(1_000), "1,000");
    assert_eq!(thousands(30_400), "30,400");
    assert_eq!(thousands(1_234_567), "1,234,567");
}

#[test]
fn renders_the_documented_file() {
    let ratings = [
        rating("greedy", 400.2, 20.1, 3_600),
        rating("v018", 1234.5, 12.3, 1_600),
        rating("random", 0.0, 0.0, 2_000),
        rating("v017", 1190.0, 11.8, 2_400),
    ];
    let board = render(
        "uttt",
        &filler(152),
        &ratings,
        "random",
        JOURNAL,
        &releases(&["v017", "v018"]),
    )
    .unwrap();
    let expected = "\
# Leaderboard

Generated by `uttt-arena leaderboard` from [league.jsonl](league.jsonl) ([ADR 0038](../../docs/adr/0038-incremental-league.md)); do not edit by hand. Bradley-Terry ratings over 152 pairings and 30,400 games, with `random` at 0 and 95% intervals. Time limits: time scale 1, tolerance 0 ms, 4 opening plies.

| Rank | Bot | Elo | 95% interval | Games | Experiment | Date |
| ---: | --- | ---: | ---: | ---: | --- | --- |
| 1 | [v018](releases/uttt-v018.rs) | +1234.5 | ±12.3 | 1,600 | [E032](journal/E032-puct-tuning.md) | 2026-10-16 |
| 2 | [v017](releases/uttt-v017.rs) | +1190.0 | ±11.8 | 2,400 | [E030](journal/E030-puct.md) | 2026-10-16 |
| 3 | greedy | +400.2 | ±20.1 | 3,600 | baseline | |
| 4 | random | 0.0 | anchor | 2,000 | baseline | |
";
    assert_eq!(board.text, expected);
    assert!(board.warnings.is_empty());
}

#[test]
fn ties_are_broken_by_name_and_unlinked_bots_come_last() {
    let ratings = [
        rating("zed", 10.0, 5.0, 200),
        rating("lone2", 0.0, f64::INFINITY, 200),
        rating("random", 0.0, 0.0, 400),
        rating("alpha", 10.0, 5.0, 200),
        rating("lone1", 99.0, f64::INFINITY, 200),
    ];
    let board = render(
        "uttt",
        &[pairing("alpha", "random", 100, 0, 100)],
        &ratings,
        "random",
        JOURNAL,
        &releases(&[]),
    )
    .unwrap();
    let rows: Vec<&str> = board.text.lines().skip(6).collect();
    assert_eq!(
        rows,
        [
            "| 1 | alpha | +10.0 | ±5.0 | 200 | baseline | |",
            "| 2 | zed | +10.0 | ±5.0 | 200 | baseline | |",
            "| 3 | random | 0.0 | anchor | 400 | baseline | |",
            "| — | lone1 | n/a | n/a | 200 | baseline | |",
            "| — | lone2 | n/a | n/a | 200 | baseline | |",
        ]
    );
    assert!(board.text.contains("ratings over 1 pairing and 200 games"));
}

#[test]
fn a_release_without_a_journal_row_warns() {
    let ratings = [
        rating("v099", 5.0, 5.0, 200),
        rating("random", 0.0, 0.0, 200),
    ];
    let board = render(
        "uttt",
        &[pairing("v099", "random", 100, 0, 100)],
        &ratings,
        "random",
        JOURNAL,
        &releases(&["v099"]),
    )
    .unwrap();
    assert!(board
        .text
        .contains("| 1 | [v099](releases/uttt-v099.rs) | +5.0 | ±5.0 | 200 | — | — |\n"));
    assert_eq!(board.warnings.len(), 1);
    assert!(board.warnings[0].contains("v099"));
}

