//! Bundles the real random bot, compiles the bundle on its own with rustc,
//! the way CodinGame does, and plays a turn with it. The paths are checked
//! on its readable bundle, since the minified one renames them.

use std::io::Write;
use std::process::{Command, Stdio};

#[test]
fn the_bundled_random_bot_compiles_alone_and_plays() {
    let bundle =
        cg_bundler::bundle_package("uttt-bot-random", None, cg_bundler::Options::default())
            .unwrap();
    let (header, code) = bundle.split_once('\n').unwrap();
    assert_eq!(
        header,
        "// Bundled by cg-bundler from the `uttt-bot-random` package. Minified (ADR 0045)."
    );
    assert!(
        code.lines().all(|line| !line.is_empty()
            && !line.starts_with([' ', '/'])
            // A line ends before the token that follows its 300th character.
            && line.chars().count() <= cg_bundler::minify::HARD_LINE + 50),
        "comments, indentation and blank lines must be removed, and lines kept short"
    );
    // The minified bundle renames the modules: their paths are checked in
    // the readable one, which keeps the names.
    let readable = cg_bundler::bundle_package(
        "uttt-bot-random",
        None,
        cg_bundler::Options {
            minify: false,
            ..cg_bundler::Options::default()
        },
    )
    .unwrap();
    for bundle in [&bundle, &readable] {
        assert!(
            !bundle.contains("mod tests"),
            "test modules must be dropped"
        );
    }
    assert!(readable.contains("mod cg_core {"));
    assert!(
        readable.contains("use crate::cg_core::rng::"),
        "paths were not rewritten"
    );
    assert!(cg_bundler::cg_size(&bundle) < cg_bundler::SIZE_LIMIT);

    let dir = std::env::temp_dir().join(format!("cg-bundler-random-{}", std::process::id()));
    std::fs::create_dir_all(&dir).unwrap();
    let source = dir.join("random.rs");
    let binary = dir.join("random");
    std::fs::write(&source, &bundle).unwrap();
    let compiled = Command::new("rustc")
        .args(["--edition", "2021", "-O", "--crate-type", "bin", "-o"])
        .arg(&binary)
        .arg(&source)
        .output()
        .unwrap();
    assert!(
        compiled.status.success(),
        "the bundle does not compile:\n{}",
        String::from_utf8_lossy(&compiled.stderr)
    );

    let mut bot = Command::new(&binary)
        .env("CG_SEED", "3")
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()
        .unwrap();
    bot.stdin
        .take()
        .unwrap()
        .write_all(b"-1 -1\n3\n4 4\n0 0\n8 8\n")
        .unwrap();
    let output = bot.wait_with_output().unwrap();
    let answer = String::from_utf8(output.stdout).unwrap();
    assert!(
        ["4 4\n", "0 0\n", "8 8\n"].contains(&answer.as_str()),
        "{answer:?}"
    );
}

#[test]
fn keep_comments_gives_the_readable_bundle() {
    let options = |minify| cg_bundler::Options {
        format: true,
        minify,
    };
    let readable = cg_bundler::bundle_package("uttt-bot-random", None, options(false)).unwrap();
    let minified = cg_bundler::bundle_package("uttt-bot-random", None, options(true)).unwrap();
    assert!(readable.starts_with(
        "// Bundled by cg-bundler from the `uttt-bot-random` package. Do not edit this file:\n"
    ));
    assert!(readable.contains("\n//! "), "doc comments are kept");
    assert!(readable.contains("\n    "), "indentation is kept");
    // Only the readable bundle needs the `allow`: the minifier removes what
    // is unused.
    assert!(readable.contains("#[allow(dead_code, unused_imports)]\nmod cg_core {"));
    assert!(!minified.contains("allow(dead_code"));
    assert!(minified.len() < readable.len());
}
